function localizeMonths(text: string, lang: string): string {
  if (lang !== "uz") return text;
  return text
    .replace(/до\s+(\d+)\s*месяцев/gi, "$1 oygacha")
    .replace(/до\s+(\d+)\s*мес\./gi, "$1 oygacha")
    .replace(/до\s+(\d+)\s*мес\b/gi, "$1 oygacha")
    .replace(/свыше\s+(\d+)\s*месяцев/gi, "$1 oydan ortiq")
    .replace(/свыше\s+(\d+)\s*мес\./gi, "$1 oydan ortiq")
    .replace(/не более\s+(\d+)\s*мес\./gi, "$1 oydan ko'p emas")
    .replace(/не более\s+(\d+)\s*мес\b/gi, "$1 oydan ko'p emas")
    .replace(/(\d+)\s*месяцев/gi, "$1 oy")
    .replace(/(\d+)\s*мес\./gi, "$1 oy")
    .replace(/(\d+)\s*мес\b/gi, "$1 oy")
    .replace(/разовый кредит/gi, "bir martalik kredit")
    .replace(/револьверный кредит/gi, "revolverli kredit")
    .replace(/для пополнения оборотных средств/gi, "aylanma vositalarni to'ldirish uchun")
    .replace(/для приобретения основных средств/gi, "asosiy vositalarni sotib olish uchun");
}

